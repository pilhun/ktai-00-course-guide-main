# 변수는 값을 다시 사용하기 위해 붙인 이름입니다. =는 오른쪽 값을 왼쪽 이름에 저장합니다.
name = "민지"  # 따옴표로 묶은 글자는 문자열입니다.
age = 20  # 소수점 없는 수는 정수입니다.
height = 165.5  # 소수점이 있는 수는 실수입니다.
# 변수 이름에는 따옴표를 붙이지 않습니다. 이름에 저장한 값이 출력됩니다.
print("이름:", name)
print("나이:", age)
print("키:", height)
# type은 값의 종류를 알려 주는 Python 기본 기능입니다.
print(type(name))
print(type(age))
print(type(height))
